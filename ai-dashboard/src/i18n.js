const DICTS = { vi: VI, en: EN };
let lang = "vi";

export const setLang = (l) => { lang = DICTS[l] ? l : "vi"; };
export const getLang = () => lang;

/** t("key", {a:1}) — thieu key thi tra chinh key de de phat hien. */
export function t(key, params) {
  const s = DICTS[lang][key] ?? DICTS.vi[key] ?? key;
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? String(params[k]) : m));
}

/** Cac chuoi phu thuoc locale: so, phan tram, ngay. */
export const locale = () => (lang === "vi" ? "vi-VN" : "en-US");

/** Ngay ngan: 08/09 (vi) | Sep 8 (en) */
export function shortDate(d) {
  const dt = d instanceof Date ? d : new Date(d);
  return lang === "vi"
    ? `${String(dt.getUTCDate()).padStart(2, "0")}/${String(dt.getUTCMonth() + 1).padStart(2, "0")}`
    : dt.toLocaleDateString("en-US", { month: "short", day: "numeric", timeZone: "UTC" });
}

/** Ngay day du: 08/09/2026 (vi) | Sep 8, 2026 (en) */
export function longDate(d) {
  const dt = d instanceof Date ? d : new Date(d);
  return lang === "vi"
    ? `${String(dt.getUTCDate()).padStart(2, "0")}/${String(dt.getUTCMonth() + 1).padStart(2, "0")}/${dt.getUTCFullYear()}`
    : dt.toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric", timeZone: "UTC" });
}

/** Ap dung cho moi phan tu co data-i18n / data-i18n-html / data-i18n-ph. */
export function applyStaticI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
}
